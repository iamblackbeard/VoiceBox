import { KokoroTTS } from 'kokoro-js';
import fs from 'fs';

function floatTo16BitPCM(output: DataView, offset: number, input: Float32Array) {
  for (let i = 0; i < input.length; i++, offset += 2) {
    const s = Math.max(-1, Math.min(1, input[i] as number));
    output.setInt16(offset, s < 0 ? s * 0x8000 : s * 0x7FFF, true);
  }
}

function writeString(view: DataView, offset: number, string: string) {
  for (let i = 0; i < string.length; i++) {
    view.setUint8(offset + i, string.charCodeAt(i));
  }
}

function encodeWAV(samples: Float32Array, sampleRate: number): Blob {
  const buffer = new ArrayBuffer(44 + samples.length * 2);
  const view = new DataView(buffer);

  writeString(view, 0, 'RIFF');
  view.setUint32(4, 36 + samples.length * 2, true);
  writeString(view, 8, 'WAVE');
  writeString(view, 12, 'fmt ');
  view.setUint32(16, 16, true);
  view.setUint16(20, 1, true);
  view.setUint16(22, 1, true);
  view.setUint32(24, sampleRate, true);
  view.setUint32(28, sampleRate * 2, true);
  view.setUint16(32, 2, true);
  view.setUint16(34, 16, true);
  writeString(view, 36, 'data');
  view.setUint32(40, samples.length * 2, true);

  floatTo16BitPCM(view, 44, samples);

  return new Blob([view], { type: 'audio/wav' });
}

async function main() {
  console.log("Loading model...");
  const tts = await KokoroTTS.from_pretrained('onnx-community/Kokoro-82M-v1.0-ONNX', {
    dtype: 'q8',
  });
  
  console.log("Generating audio...");
  const text = "Hello from the script test.";
  const audio = await tts.generate(text, { voice: "af_heart" });
  
  console.log("Got audio with length:", audio.audio.length);
  if (audio.audio.length === 0) {
    throw new Error("Empty audio generated!");
  }
  
  const wavBlob = encodeWAV(audio.audio, audio.sampling_rate);
  const buffer = await wavBlob.arrayBuffer();
  fs.writeFileSync('test-audio.wav', Buffer.from(buffer));
  console.log("Success! Audio saved to test-audio.wav.");
}

main().catch(console.error);
